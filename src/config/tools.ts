function imgTool(
  overrides: Pick<
    Tool,
    | "slug"
    | "title"
    | "navLabel"
    | "acceptedFileTypes"
    | "acceptedMime"
    | "defaultTargetSize"
    | "defaultTargetUnit"
    | "relatedSlugs"
  > & { outputFormat?: Tool["outputFormat"]; formatWord: string; extraFaq?: Tool["faq"] }
): Tool {
  const label =
    overrides.defaultTargetUnit === "MB"
      ? `${overrides.defaultTargetSize} MB`
      : `${overrides.defaultTargetSize} KB`;
  const sizeKB =
    overrides.defaultTargetUnit === "MB"
      ? (overrides.defaultTargetSize || 1) * 1024
      : overrides.defaultTargetSize || 100;
  const input = { label, sizeKB, formatWord: overrides.formatWord };
  return {
    slug: overrides.slug,
    title: overrides.title,
    navLabel: overrides.navLabel,
    category: "image-compress",
    engine: "image-target-size",
    acceptedFileTypes: overrides.acceptedFileTypes,
    acceptedMime: overrides.acceptedMime,
    outputFormat: overrides.outputFormat || "keep",
    defaultTargetSize: overrides.defaultTargetSize,
    defaultTargetUnit: overrides.defaultTargetUnit,
    allowCustomTarget: true,
    maxFileSizeMB: 20,
    clientSideOnly: true,
    seoTitle: `${overrides.title} Online Free | CompNivi`,
    metaDescription: `${overrides.title.replace(" Online", "")} for free in your browser. Fast, private, no upload required. Preview before you download.`,
    intro: buildImageIntro(input),
    contentSections: buildImageContentSections(input),
    tips: buildImageTips(input),
    faq: [...buildImageFaq(input), ...(overrides.extraFaq || [])],
    relatedSlugs: overrides.relatedSlugs,
  };
}

